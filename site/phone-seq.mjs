import { chromium } from 'playwright'
const b = await chromium.launch({ channel: 'msedge', args: ['--autoplay-policy=no-user-gesture-required'] })
const page = await (await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })).newPage()
const errs = []; page.on('pageerror', e => errs.push(String(e)))
await page.goto('http://localhost:5190/', { waitUntil: 'networkidle' }); await page.waitForTimeout(3200)
const enter = page.getByRole('button', { name: /Μπες/ }); if (await enter.count()) await enter.first().click({ force: true })
await page.waitForTimeout(2500); await page.screenshot({ path: '../shots/ph-0-film.png' })
await page.evaluate(() => { const v = document.querySelector('#hero video'); if (v) v.currentTime = v.duration - 0.05 })
await page.waitForTimeout(900); await page.screenshot({ path: '../shots/ph-1-cut.png' })
await page.waitForTimeout(1800); await page.screenshot({ path: '../shots/ph-2-tram.png' })
await page.waitForTimeout(1300); await page.screenshot({ path: '../shots/ph-3-crash.png' })
await page.waitForTimeout(2200); await page.screenshot({ path: '../shots/ph-4-hub.png' })
await page.evaluate(() => window.scrollTo(0, 1400)); await page.waitForTimeout(1200); await page.screenshot({ path: '../shots/ph-5-bar.png' })
console.log(errs)
await b.close()
